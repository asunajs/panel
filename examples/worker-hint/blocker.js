// 「跑几分钟的日常」的替身 —— 那个会把人挡住的任务。
//
// 每秒触发一次，每次**忙等 BLOCK_MS**（CPU 密集，占满它那条引擎线程）。
//
// # 为什么用 cron 的整秒网格，而不是 `@every 1s`
//
// 这是实测踩到的坑：`@every` 的网格是「加载时刻 + 周期」（比如 .468），
// 而抢兑夹具用的是 cron（整秒 .000）—— 两者**永远不会撞上**，于是夹具
// 根本挡不住人，测试看起来「通过」其实什么都没测到。第一版就是这么写的，
// 一次跑出 139ms、下一次跑出 9ms，全看启动时刻落在哪儿。
//
// 改用 `*/1 * * * * *` 之后，两个任务在同一条 1 秒网格上：
// 同一个 tick 里 `blocker` 先注册、先触发（插件按名字排序加载），
// 忙等 300ms，后面的抢兑任务就必然吃到这 300ms。
//
// # 为什么用忙等而不是 http_fetch
//
// 忙等是确定性的，不依赖网络；而且两者对引擎的影响完全一样 —— 引擎线程被
// 同步调用占住，期间同一条线程上谁也跑不了。
//
// # 为什么不是真跑三分钟
//
// 验收要证明的是**隔离**，而隔离与阻塞时长无关 —— 只要两条任务不在同一条
// 线程上，挡多久都不影响。跑三分钟只会让脚本慢三分钟。
// 300ms 已经远超抢兑那几十毫秒的窗口，足够暴露「同一条线程」的情况。

import { register_cron, log } from 'host-api';

const BLOCK_MS = 300;

let runs = 0;

register_cron('block', '*/1 * * * * *', function () {
    const t = Date.now();
    while (Date.now() - t < BLOCK_MS) {
        // 故意空转：占住它那条引擎线程
    }
    runs++;
    log(`blocker 第 ${runs} 次占住线程 ${BLOCK_MS}ms`);
});
