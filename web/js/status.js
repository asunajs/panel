/**
 * 任务状态 → 徽章样式 + **给人看的字**，以及时刻的显示格式。
 *
 * # 为什么单独一个模块
 *
 * 这份映射原来长在 `views/task-list.js` 里（私有常量），而仪表盘的「任务概览」
 * 也有一列状态 —— 它当时是**直接把后端原值吐出来**的，于是同一个界面里
 * 列表页写「运行中」、仪表盘写 `running`。一处写中文、一处露英文，看起来
 * 就像"没设计过"；两处各存一份映射迟早还会漂，所以抽出来共用。
 *
 * # 取值
 *
 * 后端保证的就是下面这几个（见 `src/web.rs` 的 `job_rows`）。
 * 认不出来的状态**原样显示**，不猜也不吞 —— 新增一个状态时，
 * 宁可看到一个陌生的英文词，也不要看到「未知」而不知道到底是哪个。
 */

export const STATUS_MAP = {
  // ⚠ `running` 是后端的**任务状态**，意思是"正常在排班里"（没暂停 / 没熔断 /
  //   上次没出错），**不是**"这会儿正在执行"。
  //
  //   原来这里写「运行中」，于是用户合理地问："这些任务只要到点醒一次，
  //   为啥一直显示运行中？只有带路由的插件才需要常驻吧" —— 问得对。
  //   真正的状态是：
  //     · 两次触发之间，任务**什么都不做**（引擎只在到点时叫它一次）；
  //     · 只有注册了 `on_tick` / 路由的插件才是"常驻"的，那是插件层面的属性，
  //       不是这一列要表达的东西。
  //   所以这格里写「已启用」，并把"到点才跑"挂到 title 上。
  running: { cls: 'running', text: '已启用', title: '会按排班到点跑一次；两次之间不占线程、什么都不做' },
  paused: { cls: 'idle', text: '已暂停', title: '不会到点跑（去任务页恢复）' },
  tripped: { cls: 'failed', text: '已熔断', title: '连续失败太多次，面板先把它停一会儿' },
  error: { cls: 'failed', text: '执行出错', title: '上一次跑到一半抛错了，下次到点还会再试' },
  idle: { cls: 'idle', text: '待触发', title: '还没排上（没有下次触发时刻）' },
  // 面板删掉的（墓碑）：插件代码仍然声明它，所以它还在库里但不调度
  deleted: { cls: 'idle', text: '已删除', title: '插件代码里还声明着它，但面板不再调度' },
};

/** 状态 → `{cls, text}`。认不出来的给中性样式 + 原值。 */
export function statusBadge(status) {
  return STATUS_MAP[status] || { cls: 'idle', text: String(status ?? '—') };
}

/**
 * 一次**运行**的结果 → 徽章 + 一行说明。
 *
 * 为什么不复用 statusBadge()：那个说的是**任务**状态（已启用 / 已暂停 / 已熔断），
 * 这里说的是**某一次执行**的结果（成功 / 失败 / 已停止）。两套词混在一起，用户会
 * 以为"任务出错了"，其实只是上一次跑得不顺。
 *
 * 三种情况里最容易做错的是「已停止」：手动停止（或超出执行预算）时，QuickJS 抛的是
 * `InternalError: interrupted` **加一整段 JS 堆栈**。原样显示出来就是一屏红字，看着
 * 像面板炸了 —— 而事实是用户自己按了停止。所以这里把它单独归一类：中性灰徽章 +
 * 一句人话，不展示堆栈（堆栈去日志里看，那才是排查的地方）。
 */
const INTERRUPTED = /interrupt/i;

export function runOutcome(run) {
  const r = run || {};
  if (r.ok === null || r.ok === undefined) {
    return { cls: 'warning', text: '没跑完', note: '' };
  }
  if (r.ok) return { cls: 'ok', text: '成功', note: '' };
  const err = String(r.error || '');
  // 后端从「停止不算失败」那一版起直接给 stopped 标记；老记录只有那句 interrupted，
  // 所以两个都认 —— 升级后不该让昨天那条记录突然变回红色的失败。
  if (r.stopped === true || INTERRUPTED.test(err)) {
    return {
      cls: 'stopped',
      text: '已停止',
      // 引擎层「手动停止」和「超出执行预算」是同一个中断，前端分不出来 ——
      // 所以两种原因都写上。只说"手动停止"会在超预算时骗人。
      note:
        '这次执行被中途停下：手动「停止」，或者超出执行预算。' +
        '这不是任务本身报错 —— 它跑到哪一步，去「看日志」里翻。',
    };
  }
  return { cls: 'danger', text: '失败', note: err };
}

/**
 * 时刻只显示到**分钟**。
 *
 * 后端给的是 `2026-10-17 08:00:00.000`，而调度最小粒度就是分钟 ——
 * 秒和毫秒挂在表格里只是噪声（`08:00:00.000` 比 `08:00` 难扫得多）。
 * ⚠ 只截**显示**：API 那个字段原样不动（`scripts/smoke.py` 拿它做断言）。
 */
export function minuteOf(ts) {
  if (!ts) return '—';
  return String(ts).replace('T', ' ').slice(0, 16);
}
