out.alloc = ALLOCS.map((c) => {
  const sizeArg = c.size === 'NaN' ? NaN : c.size === 'Infinity' ? Infinity : c.size;
  const r = rec(() => {
    if (c.fill === undefined) return hex(Buffer.alloc(sizeArg));
    const f = c.fill;
    if (f.kind === 'number') return hex(Buffer.alloc(sizeArg, f.n));
    if (f.kind === 'bytes') return hex(Buffer.alloc(sizeArg, Buffer.from(bytes(f.bytes))));
    return hex(Buffer.alloc(sizeArg, str(f.units), f.encoding));
  });
  return { ...c, size: sizeToken(c.size), ...pick(r, 'hex') };
});

