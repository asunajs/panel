#!/usr/bin/env node
// 生成 src/jscompat/vectors/buffer.json —— Buffer 兼容层的期望值来自**真的 Node**。
//
// 为什么要有这个脚本：兼容层的目标是「同一份插件在 QuickJS 与 Node 下行为一致」。
// 手写期望值等于把「我以为 Node 会这样」固化进测试；跑真 Node 才是把 Node 的
// **实际行为**固化进来（这一版就被实测纠正过好几处：fill 的负偏移在 Node 24
// 是抛错的、base64 解码遇到 '=' 就停但会跳过非法字符、'ascii' 写入等价 latin1
// 而读取会 & 0x7f……）。改了 buffer.js 之后重跑它，差异会直接暴露。
//
// 用法：node scripts/gen-vectors-buffer.mjs
//
// ⚠ 生成结果要提交进仓库：跑测试的机器（CI / 离线构建）不需要装 Node。
//
// 错误用例只记**错误的名字**（TypeError / RangeError），不记 code：Node 对
// 越界读写的 code 是 ERR_BUFFER_OUT_OF_BOUNDS，而面板统一给 ERR_OUT_OF_RANGE
// （见 buffer.js 文件头「与 Node 的已知差异」）；code 由 buffer_test.rs 单独断言。

