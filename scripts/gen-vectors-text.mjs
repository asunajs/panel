#!/usr/bin/env node
// 生成 src/jscompat/vectors/text.json —— 期望值来自**真的 Node**。
//
// 为什么要有这个脚本：兼容层的意义是「同一份插件在 QuickJS 与 Node 下行为一致」。
// 手写期望值等于把"我以为 Node 会这样"固化进测试里；用 Node 生成，才是把
// **Node 的实际行为**固化进来。改了 text.js 之后重跑它，差异会直接暴露。
//
// 用法：node scripts/gen-vectors-text.mjs
//
// ⚠ 生成结果要提交进仓库：跑测试的机器（CI / 离线构建）不需要装 Node。

import { writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const outFile = join(here, '..', 'src', 'jscompat', 'vectors', 'text.json');

/** JS 字符串 → UTF-16 码元数组。**不能直接用字符串**：孤立代理项无法在 JSON 里往返。 */
const units = (s) => Array.from({ length: s.length }, (_, i) => s.charCodeAt(i));
const str = (u) => String.fromCharCode(...u);
const hex = (u8) => Buffer.from(u8).toString('hex');
const bytes = (h) => Uint8Array.from(h.match(/../g) || [], (x) => parseInt(x, 16));

const ENCODE_INPUTS = [
    '',
    'abc',
    '你好',
    '😀🎵',
    '\u0000',
    'a\u0000b',
    'é',
    'ÿ',
    '€',
    '\uFEFFhello',
    'a\uFEFFb',
    '\uFFFD',
    '\u{10FFFF}',
    // 孤立代理项：TextEncoder 必须产出 U+FFFD（EF BF BD），不是抛错
    '\uD800',
    'a\uD800b',
    '\uDC00',
    'a\uDC00\uD800b',
    '😀\uD800',
];

const DECODE_INPUTS = [
    '616263',                 // abc
    'efbbbf68656c6c6f',       // BOM + hello
    'efbbbf',                 // 只有 BOM
    '61efbbbf62',             // BOM 在中间（不该被吃）
    'e4bda0e5a5bd',           // 你好
    'f09f9880',               // 😀
    '00',                     // NUL
    '80',                     // 裸续字节
    'c0af',                   // 过长编码
    'c1bf',                   // 过长编码
    'e08080',                 // 过长 3 字节
    'eda080',                 // 代理项编码（UTF-8 不该出现）
    'f4908080',               // > U+10FFFF
    'f5808080',               // 首字节就超范围
    'f09f98',                 // 截断（3/4 字节）
    'e4bd',                   // 截断（2/3 字节）
    'c2',                     // 截断（1/2 字节）
    'e4bda0e4',               // 合法 + 半截
    '61ff62',                 // 中间一个 0xFF
    'fe',                     // 0xFE
    'ff',                     // 0xFF
    'f09f9880f09f9880',       // 两个 astral
    'efbfbd',                 // 本来就是 U+FFFD
];

const FATAL_INPUTS = ['80', 'c0af', 'eda080', 'f4908080', 'e4bd', '61ff'];

const ENCODE_INTO_CASES = [
    ['abc', 2],
    ['abc', 3],
    ['abc', 5],
    ['😀', 3],
    ['😀', 4],
    ['a😀', 5],
    ['你好', 4],
    ['', 0],
    ['é', 1],
    ['é', 2],
];

const BTOA_INPUTS = ['', 'abc', '\u0000\u00ff', 'A man is at the bar', 'ÿÿÿÿ', 'ÿ\u0000\u007f'];
// btoa 的失败用例：> 0xFF 的码元
const BTOA_THROWS = ['你好', '€', '😀', 'a€b'];
const ATOB_INPUTS = ['', 'YWJj', 'YQ', 'YQ==', ' Y W J j ', 'YWJj\nZA==', '////', 'AA==', 'YWJjZA'];
// atob 的失败用例：注意 node 会**先去掉 ASCII 空白**再判 —— 'Y W = =' 是合法的（= 'YQ=='）。
const ATOB_THROWS = ['!!!!', 'a', 'YQ=', 'YQ===', 'YQ==extra', 'AA=', '=AAA', '_-w', '_w'];

const enc = new TextEncoder();

const out = {
    note: 'generated by scripts/gen-vectors-text.mjs on node ' + process.version,
    encode: ENCODE_INPUTS.map((s) => ({ units: units(s), hex: hex(enc.encode(s)) })),
    decode: [],
    encode_into: [],
    btoa: BTOA_INPUTS.map((s) => {
        let v = null;
        try { v = btoa(s); } catch (e) { v = '!THROW:' + e.name; }
        return { units: units(s), out: v };
    }),
    atob: ATOB_INPUTS.map((s) => {
        let unitsOut = null;
        try { unitsOut = units(atob(s)); } catch (e) { unitsOut = ['!THROW:' + e.name]; }
        return { input: s, units: unitsOut };
    }),
    btoa_throws: BTOA_THROWS.map((s) => {
        let name = null;
        try { btoa(s); } catch (e) { name = e.name; }
        return { units: units(s), name };
    }),
    atob_throws: ATOB_THROWS.map((s) => {
        let name = null;
        try { atob(s); } catch (e) { name = e.name; }
        return { input: s, name };
    }),
    fatal_throws: FATAL_INPUTS.map((h) => {
        let name = null;
        try { new TextDecoder('utf-8', { fatal: true }).decode(bytes(h)); } catch (e) { name = e.name; }
        return { bytes: h, name };
    }),
};

for (const h of DECODE_INPUTS) {
    for (const ignoreBOM of [false, true]) {
        const text = new TextDecoder('utf-8', { ignoreBOM }).decode(bytes(h));
        out.decode.push({ bytes: h, fatal: false, ignoreBOM, units: units(text) });
    }
}

for (const [s, size] of ENCODE_INTO_CASES) {
    const buf = new Uint8Array(size);
    const r = enc.encodeInto(s, buf);
    out.encode_into.push({ units: units(s), size, read: r.read, written: r.written, hex: hex(buf) });
}

mkdirSync(dirname(outFile), { recursive: true });
writeFileSync(outFile, JSON.stringify(out, null, 2) + '\n');
console.log('wrote', outFile, '—', Object.entries(out).filter(([k]) => k !== 'note').map(([k, v]) => k + ':' + v.length).join(' '));
